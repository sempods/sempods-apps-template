#!/usr/bin/env node
// Builds every app with a published profile into its path of one static site
// folder, site-dist/, with a page for each route, and writes the overview and
// the host's routing files: 404.html, and _redirects for resource patterns.
// Beside each app it publishes the app's descriptions (app.jsonld,
// client.json, did.json) and the list of its files (build.json), and at the
// root the site catalog (apps.jsonld) and _headers. apps/<id>/dist keeps the
// app's local build.
// Usage: pnpm run build-site [--profile production|preview]
//        (or SEMPODS_SITE_PROFILE=<profile> in the host's environment)
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { SITE_PROFILES, siteIdentity } from './lib/apps.mjs';
import { describedApps } from './lib/describe.mjs';
import { PROFILE_MODES, staleGenerated } from './lib/generate.mjs';
import { PNG_ICONS } from './lib/icon.mjs';
import { ifPresent, readJson, writeJson } from './lib/json.mjs';
import { renderNotFound, renderOverview } from './lib/overview.mjs';
import { repositoryRoot } from './lib/paths.mjs';
import { pnpm, scriptArgs } from './lib/pnpm.mjs';
import {
  APP_DESCRIPTION,
  appDescription,
  appIri,
  BUILD_LIST,
  buildList,
  CLIENT_DOCUMENT,
  clientDocument,
  headersFile,
  identifierProblems,
  SITE_CATALOG,
  siteCatalog,
} from './lib/published.mjs';
import { SDK } from './lib/sdk.mjs';
import { textCompleteness } from './lib/texts.mjs';

export const SITE_DIR = 'site-dist';

/** Runs the app's own build script with a site mode into `outDir`. */
function appBuild(appDir, mode, outDir) {
  // pnpm appends these to the script's final `vite build`. The output path is
  // relative to the app, so no user directory name passes through the Windows
  // shell (lib/pnpm.mjs).
  const args = [
    ...['run', 'build', '--mode', mode],
    ...['--outDir', relative(appDir, outDir), '--emptyOutDir'],
  ];
  return pnpm(args, { cwd: appDir }).status === 0;
}

// Paths build-site reserves in each app's output, so an app's own copies are
// left out: the documents written here, host files that hosts read only at
// the site root (Cloudflare would serve a nested 404.html), and the callback:
// `callback.html` is written here, and an extensionless `callback` would
// answer the callback path before it.
const RESERVED = [
  'did.json',
  APP_DESCRIPTION,
  CLIENT_DOCUMENT,
  BUILD_LIST,
  '_redirects',
  '_headers',
  '404.html',
  'callback',
  'callback.html',
];

const REDIRECTS_HEADER = `# Generated by pnpm run build-site from the resource patterns in apps.json.
# Each line serves an app's page for its resource addresses.
`;

/** Removes a file or directory and reports whether there was one. */
const removeIfPresent = (path) =>
  ifPresent(() => rmSync(path, { recursive: true }) ?? true) ?? false;

/** Copies a file and reports whether there was one to copy. */
const copyIfPresent = (from, to) =>
  ifPresent(() => copyFileSync(from, to) ?? true) ?? false;

/**
 * The Apache-2.0 notices of the SDK packages the app declares, which travel
 * with the published code.
 */
function copyLicences(roots, appOut, appId) {
  const { dependencies = {} } = readJson(join(roots[0], 'package.json'));
  for (const pkg of SDK.filter((name) => dependencies[name])) {
    const to = join(appOut, 'licenses', pkg.split('/')[1]);
    mkdirSync(to, { recursive: true });
    const from = roots
      .map((base) => join(base, 'node_modules', pkg))
      .find((dir) => copyIfPresent(join(dir, 'LICENSE'), join(to, 'LICENSE')));
    if (!from)
      throw new Error(
        `${pkg} with its LICENSE is not installed for apps/${appId}; run pnpm install.`,
      );
    copyIfPresent(join(from, 'NOTICE'), join(to, 'NOTICE'));
  }
}

/**
 * The overview entry of a built app, from its published description, so the
 * overview shows what every other reader of app.jsonld sees.
 */
function overviewEntry(app, description, outDir) {
  const details = description.subjectOf?.map((text) => [text.inLanguage, text.text]);
  return {
    id: app.id,
    href: app.path,
    lang: app.about.lang,
    name: description.name,
    ...(description.description ? { description: description.description } : {}),
    ...(details ? { details: Object.fromEntries(details) } : {}),
    ...(description.applicationCategory ? { categories: description.applicationCategory } : {}),
    languages: description.inLanguage,
    installable: app.pwa === true,
    // The overview's cards are small: the smaller icon, by path, so the
    // overview also works on another origin, such as a local preview.
    ...(existsSync(join(outDir, PNG_ICONS[0])) ? { icon: `${app.path}${PNG_ICONS[0]}` } : {}),
  };
}

/** Builds the site for `profile`; returns what it built and any warnings. */
export function buildSite(root, { profile = 'production', build = appBuild } = {}) {
  if (!SITE_PROFILES.includes(profile))
    throw new Error(`The profile is one of ${SITE_PROFILES.join(', ')}.`);
  const { apps, site, catalog } = describedApps(root);
  if (!site?.[profile])
    throw new Error(
      `apps.json has no site.${profile}; run pnpm run configure-site first.`,
    );
  if (apps.length === 0) throw new Error('There are no apps to publish yet.');
  const out = join(root, SITE_DIR);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });

  // A hand edit of apps.json would build one identity and publish another.
  for (const app of apps) {
    const stale = staleGenerated(join(root, 'apps', app.id), app, site);
    if (stale.length > 0)
      throw new Error(
        `apps/${app.id}/${stale[0]} does not match apps.json, apps/${app.id}/app.json or the app's theme; run pnpm run regenerate.`,
      );
    // Readers get every text in every language the app is shown in.
    const problems = textCompleteness(root, app);
    if (problems.length > 0)
      throw new Error(
        `${problems.join('; ')}. Fix the texts as pnpm run check explains, then build again.`,
      );
  }
  const origin = site[profile];
  const descriptions = [];

  const entries = [];
  const warnings = [];
  const rewrites = [];
  for (const app of apps) {
    const appDir = join(root, 'apps', app.id);
    const appOut = join(out, app.id);
    if (!build(appDir, PROFILE_MODES[profile], appOut))
      throw new Error(`apps/${app.id}: the build failed.`);
    const index = join(appOut, 'index.html');
    const html = ifPresent(() => readFileSync(index, 'utf8'));
    if (html === undefined)
      throw new Error(
        `apps/${app.id}: the build wrote no index.html to ${SITE_DIR}/${app.id}; the app's build script must end with vite build.`,
      );

    for (const file of RESERVED)
      if (removeIfPresent(join(appOut, file)))
        warnings.push(
          `apps/${app.id}/public/${file} is not published: build-site reserves this path.`,
        );

    // Some Pods resolve the did:web document before they accept the app.
    const { clientId, redirectUri } = siteIdentity(origin, app);
    const did = { '@context': 'https://www.w3.org/ns/did/v1', id: clientId };
    writeJson(join(appOut, 'did.json'), did);
    // The largest icon, at a fixed address the store and the client document
    // point to.
    const icon = existsSync(join(appOut, PNG_ICONS.at(-1)))
      ? `${appIri(origin, app)}${PNG_ICONS.at(-1)}`
      : undefined;
    const description = appDescription(root, app, origin, {
      icon,
      publisher: catalog?.publisher,
    });
    const client = clientDocument(app, origin, { icon });
    const problems = identifierProblems(app, origin, {
      description,
      client,
      did,
      manifest: ifPresent(() =>
        readJson(join(appOut, 'manifest.webmanifest')),
      ),
    });
    if (problems.length > 0) throw new Error(problems.join('; '));
    writeJson(join(appOut, APP_DESCRIPTION), description);
    writeJson(join(appOut, CLIENT_DOCUMENT), client);
    descriptions.push(description);
    copyLicences([appDir, root], appOut, app.id);

    // The callback must answer 200 at its exact path with its query intact.
    // Static hosts serve <path>.html for an extensionless path; Netlify does
    // so without a redirect.
    const callback = new URL(redirectUri).pathname;
    writeFileSync(join(out, `${callback.slice(1)}.html`), html);
    // Each route answers the same way from a copy of the page, so the host
    // needs no rewrite for it and unknown paths still show the not-found page.
    // A route with several segments gets its copy in a subfolder.
    const routes = app.routes ?? [];
    for (const route of routes)
      if (['', '.html'].some((ext) => existsSync(join(appOut, route + ext))))
        throw new Error(
          `apps/${app.id}: the route ${route} collides with ${route} in the app's build output; rename one of them.`,
        );
    for (const route of routes) {
      mkdirSync(dirname(join(appOut, route)), { recursive: true });
      writeFileSync(join(appOut, `${route}.html`), html);
    }
    // Resource patterns have no file per address: the host rewrites exactly
    // these addresses to the page, after the published files.
    for (const pattern of app.resources ?? [])
      rewrites.push(`${app.path}${pattern} ${app.path}index.html 200`);

    entries.push(overviewEntry(app, description, appOut));
    // Last, so it lists every file the app publishes.
    writeJson(join(appOut, BUILD_LIST), buildList(appOut, app));
  }

  writeJson(join(out, SITE_CATALOG), siteCatalog(origin, descriptions, catalog));
  writeFileSync(join(out, '_headers'), headersFile(apps));

  writeFileSync(join(out, 'index.html'), renderOverview(entries, catalog));
  // Hosts serve it for unknown paths; without it, Cloudflare Pages would serve
  // the overview for every unknown path.
  writeFileSync(join(out, '404.html'), renderNotFound(entries, catalog));
  // Netlify and Cloudflare Pages read it at the site root; a placeholder
  // matches one segment, and a published file at the address wins.
  if (rewrites.length > 0)
    writeFileSync(
      join(out, '_redirects'),
      `${REDIRECTS_HEADER}${rewrites.join('\n')}\n`,
    );
  return { apps, site, warnings, rewrites };
}

function main() {
  const { values } = parseArgs({
    args: scriptArgs(),
    options: { profile: { type: 'string' } },
  });
  const root = repositoryRoot();
  const profile =
    values.profile ?? process.env.SEMPODS_SITE_PROFILE ?? 'production';
  const { apps, site, warnings, rewrites } = buildSite(root, { profile });
  for (const warning of warnings) console.warn(`build-site: ${warning}`);
  console.log(`\nBuilt ${SITE_DIR}/ for ${site[profile]} (${profile}):`);
  for (const app of apps) console.log(`  ${site[profile]}${app.path}`);
  if (rewrites.length > 0)
    console.log(
      `\n${SITE_DIR}/_redirects serves the resource addresses; the host must read it (Netlify, Cloudflare Pages).`,
    );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    main();
  } catch (error) {
    console.error(`build-site: ${error.message}`);
    process.exitCode = 1;
  }
}
