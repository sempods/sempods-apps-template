#!/usr/bin/env node
// Replaces reference/sempods-sdk/ with the SDK's documentation and examples at
// the release tag of the given version. Usage: node .sempods/scripts/sdk-snapshot.mjs 0.2.0
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'sempods/sempods-typescript';
// What app authors need. SDK contributor instructions are left out.
const INCLUDE = [
  'README.md',
  'LICENSE',
  'NOTICE',
  'docs',
  'examples',
  'packages/app-sdk/README.md',
  'packages/client-sdk/README.md',
];
const EXCLUDE = [/^docs\/agents\//, /(^|\/)(AGENTS|CLAUDE)\.md$/];

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: 'utf8', ...options });
  if (result.status !== 0)
    throw new Error(
      `${command} ${args.join(' ')} failed: ${result.stderr || result.stdout}`,
    );
  return result.stdout;
}

function files(dir, base = dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory()
      ? files(path, base)
      : [relative(base, path).split(sep).join('/')];
  });
}

/** Points relative Markdown links that leave the snapshot to the pinned source. */
export function pinOutsideLinks(source, file, present, tag) {
  const rewrite = (target) => {
    if (/^([a-z][a-z0-9+.-]*:|#|\/)/i.test(target)) return target;
    const [path, anchor] = target.split('#');
    if (path === '') return target;
    const resolved = posix
      .normalize(posix.join(posix.dirname(file), path))
      .replace(/\/$/, '');
    if (present(resolved)) return target;
    return `https://github.com/${REPO}/blob/${tag}/${resolved}${anchor === undefined ? '' : `#${anchor}`}`;
  };
  return source
    .replace(/\]\(([^)\s]+)\)/g, (_, target) => `](${rewrite(target)})`)
    .replace(
      /^(\[[^\]]+\]:\s*)(\S+)/gm,
      (_, label, target) => `${label}${rewrite(target)}`,
    );
}

export async function snapshot(root, version) {
  const tag = `v${version}`;
  const commit = run('git', [
    'ls-remote',
    `https://github.com/${REPO}.git`,
    `refs/tags/${tag}^{}`,
  ]).split('\t')[0];
  if (!/^[0-9a-f]{40}$/.test(commit))
    throw new Error(`tag ${tag} not found in ${REPO}`);

  const work = mkdtempSync(join(tmpdir(), 'sempods-sdk-'));
  try {
    const response = await fetch(
      `https://codeload.github.com/${REPO}/tar.gz/${commit}`,
    );
    if (!response.ok)
      throw new Error(`download failed: HTTP ${response.status}`);
    writeFileSync(
      join(work, 'sdk.tgz'),
      Buffer.from(await response.arrayBuffer()),
    );
    mkdirSync(join(work, 'src'));
    run('tar', [
      '-xzf',
      join(work, 'sdk.tgz'),
      '-C',
      join(work, 'src'),
      '--strip-components=1',
    ]);

    const out = join(work, 'out');
    for (const path of INCLUDE) {
      if (!existsSync(join(work, 'src', path)))
        throw new Error(`${path} missing at ${tag}`);
      cpSync(join(work, 'src', path), join(out, path), { recursive: true });
    }
    for (const file of files(out))
      if (EXCLUDE.some((re) => re.test(file))) rmSync(join(out, file));
    const kept = new Set(files(out));
    const present = (path) =>
      kept.has(path) || [...kept].some((file) => file.startsWith(`${path}/`));
    for (const file of kept) {
      if (!file.endsWith('.md')) continue;
      const source = readFileSync(join(out, file), 'utf8');
      const pinned = pinOutsideLinks(source, file, present, tag);
      if (pinned !== source) writeFileSync(join(out, file), pinned);
    }
    writeFileSync(
      join(out, 'source.json'),
      `${JSON.stringify({ repository: REPO, version, tag, commit }, null, 2)}\n`,
    );
    writeFileSync(
      join(out, 'SOURCE.md'),
      `# sempods SDK reference snapshot

Source: [${REPO}](https://github.com/${REPO}) at tag \`${tag}\`, commit
\`${commit}\`. It matches the SDK version the apps install.

Contents: the SDK's documentation (without its contributor instructions),
examples, README files, LICENSE and NOTICE. Change: relative links to files
outside this snapshot point to the same files at \`${tag}\` on GitHub; nothing
else is changed.

Licences, as stated in NOTICE: code and examples are Apache-2.0 (LICENSE),
documentation is CC BY 4.0. They are not covered by this template's MIT-0
licence.

Generated by \`.sempods/scripts/sdk-snapshot.mjs\`. Do not edit; update the SDK
version instead.
`,
    );

    const target = join(root, 'reference', 'sempods-sdk');
    rmSync(target, { recursive: true, force: true });
    mkdirSync(dirname(target), { recursive: true });
    cpSync(out, target, { recursive: true });
    return { tag, commit, files: files(target).length };
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const version = process.argv[2];
  if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) {
    console.error('Usage: node .sempods/scripts/sdk-snapshot.mjs <version>');
    process.exit(2);
  }
  const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const result = await snapshot(root, version);
  console.log(
    `reference/sempods-sdk: ${result.files} files from ${result.tag} (${result.commit.slice(0, 12)}).`,
  );
}
